package com.bernaferrari.kmpwright.core

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.awt.image.BufferedImage
import java.io.ByteArrayOutputStream
import javax.imageio.ImageIO

class VisualDiffTest {

    @Test
    fun `identical images match`() {
        val pixels = byteArrayOf(
            255.toByte(), 0.toByte(), 0.toByte(), 255.toByte(),
            0.toByte(), 255.toByte(), 0.toByte(), 255.toByte(),
            0.toByte(), 0.toByte(), 255.toByte(), 255.toByte(),
            255.toByte(), 255.toByte(), 0.toByte(), 255.toByte()
        )
        val img = RgbaImage(2, 2, pixels)
        val result = VisualDiff.compareRgba(img, img)
        assertTrue(result.match)
        assertEquals(0.0, result.mismatchPercentage, 0.001)
        assertEquals(0L, result.differentPixels)
        assertEquals(4L, result.totalPixels)
        assertNull(result.dimensionMismatch)
    }

    @Test
    fun `single pixel diff detected`() {
        val expected = ByteArray(8) // 2x1 image: red pixel, green pixel
        expected[0] = 255.toByte(); expected[1] = 0; expected[2] = 0; expected[3] = 255.toByte()
        expected[4] = 0; expected[5] = 255.toByte(); expected[6] = 0; expected[7] = 255.toByte()

        val actual = expected.copyOf()
        // Change first pixel from red to blue
        actual[0] = 0; actual[1] = 0; actual[2] = 255.toByte()

        val img1 = RgbaImage(2, 1, expected)
        val img2 = RgbaImage(2, 1, actual)
        val result = VisualDiff.compareRgba(img1, img2)

        assertFalse(result.match)
        assertEquals(1L, result.differentPixels)
        assertEquals(2L, result.totalPixels)
        assertEquals(50.0, result.mismatchPercentage, 0.001)
    }

    @Test
    fun `dimension mismatch detected`() {
        val img1 = RgbaImage(10, 10, ByteArray(10 * 10 * 4))
        val img2 = RgbaImage(20, 5, ByteArray(20 * 5 * 4))
        val result = VisualDiff.compareRgba(img1, img2)

        assertFalse(result.match)
        assertNotNull(result.dimensionMismatch)
        assertEquals(10, result.dimensionMismatch!!.expectedWidth)
        assertEquals(10, result.dimensionMismatch!!.expectedHeight)
        assertEquals(20, result.dimensionMismatch!!.actualWidth)
        assertEquals(5, result.dimensionMismatch!!.actualHeight)
        assertEquals(100.0, result.mismatchPercentage, 0.001)
        assertNull(result.diffImage)
    }

    @Test
    fun `diff image is generated by default`() {
        val expected = ByteArray(4) { 0.toByte() } // black
        val actual = ByteArray(4) { 255.toByte() } // white
        val img1 = RgbaImage(1, 1, expected)
        val img2 = RgbaImage(1, 1, actual)

        val result = VisualDiff.compareRgba(img1, img2)
        assertNotNull(result.diffImage)
        assertEquals(4, result.diffImage!!.size)
    }

    @Test
    fun `diff image can be disabled`() {
        val expected = ByteArray(4) { 0.toByte() }
        val actual = ByteArray(4) { 255.toByte() }
        val img1 = RgbaImage(1, 1, expected)
        val img2 = RgbaImage(1, 1, actual)

        val result = VisualDiff.compareRgba(img1, img2, generateDiffImage = false)
        assertNull(result.diffImage)
    }

    @Test
    fun `diff image shows red for different pixels`() {
        val expected = ByteArray(4) { 0.toByte() }
        val actual = ByteArray(4) { 255.toByte() }
        val img1 = RgbaImage(1, 1, expected)
        val img2 = RgbaImage(1, 1, actual)

        val result = VisualDiff.compareRgba(img1, img2)
        assertNotNull(result.diffImage)
        // Red pixel: (255, 0, 0, 255)
        assertEquals(255.toByte(), result.diffImage!![0])
        assertEquals(0.toByte(), result.diffImage!![1])
        assertEquals(0.toByte(), result.diffImage!![2])
        assertEquals(255.toByte(), result.diffImage!![3])
    }

    @Test
    fun `diff image shows grayscale for matching pixels`() {
        val pixels = ByteArray(4) // gray: (128, 128, 128, 255)
        pixels[0] = 128.toByte(); pixels[1] = 128.toByte(); pixels[2] = 128.toByte(); pixels[3] = 255.toByte()
        val img = RgbaImage(1, 1, pixels)

        val result = VisualDiff.compareRgba(img, img)
        assertNotNull(result.diffImage)
        // Dimmed grayscale: original gray * 0.5 ≈ 64
        val gray = result.diffImage!![0].toInt() and 0xFF
        assertTrue(gray > 60 && gray < 70)
    }

    @Test
    fun `threshold sensitivity allows small differences`() {
        val expected = ByteArray(4)
        expected[0] = 100.toByte(); expected[1] = 100.toByte(); expected[2] = 100.toByte(); expected[3] = 255.toByte()
        val actual = ByteArray(4)
        actual[0] = 101.toByte(); actual[1] = 101.toByte(); actual[2] = 101.toByte(); actual[3] = 255.toByte()

        val img1 = RgbaImage(1, 1, expected)
        val img2 = RgbaImage(1, 1, actual)

        // With high threshold, small diff is tolerated
        val result = VisualDiff.compareRgba(img1, img2, threshold = 0.1)
        assertTrue(result.match)

        // With zero threshold, any diff is flagged
        val strictResult = VisualDiff.compareRgba(img1, img2, threshold = 0.0)
        assertFalse(strictResult.match)
    }

    @Test
    fun `1x1 images compare correctly`() {
        val pixels = ByteArray(4) { 42.toByte() }
        val img = RgbaImage(1, 1, pixels)
        val result = VisualDiff.compareRgba(img, img)
        assertTrue(result.match)
        assertEquals(1L, result.totalPixels)
    }

    @Test
    fun `RgbaImage validates dimensions`() {
        try {
            RgbaImage(2, 2, ByteArray(10)) // needs 16 bytes
            assertTrue(false) // should not reach
        } catch (e: IllegalArgumentException) {
            assertTrue(e.message!!.contains("Pixel array size"))
        }
    }

    @Test
    fun `RgbaImage validates non-negative dimensions`() {
        try {
            RgbaImage(-1, 1, ByteArray(4))
            assertTrue(false)
        } catch (e: IllegalArgumentException) {
            assertTrue(e.message!!.contains("non-negative"))
        }
    }

    @Test
    fun `DiffResult equality`() {
        val result1 = DiffResult(
            match = false,
            mismatchPercentage = 50.0,
            differentPixels = 2,
            totalPixels = 4,
            diffImage = byteArrayOf(1, 2, 3)
        )
        val result2 = DiffResult(
            match = false,
            mismatchPercentage = 50.0,
            differentPixels = 2,
            totalPixels = 4,
            diffImage = byteArrayOf(1, 2, 3)
        )
        assertEquals(result1, result2)
    }

    @Test
    fun `DimensionMismatch defaults`() {
        val dm = DimensionMismatch(100, 200, 300, 400)
        assertEquals(100, dm.expectedWidth)
        assertEquals(200, dm.expectedHeight)
        assertEquals(300, dm.actualWidth)
        assertEquals(400, dm.actualHeight)
    }

    @Test
    fun `completely different images`() {
        val expected = ByteArray(8) { 0.toByte() }
        val actual = ByteArray(8) { 255.toByte() }
        val img1 = RgbaImage(2, 1, expected)
        val img2 = RgbaImage(2, 1, actual)

        val result = VisualDiff.compareRgba(img1, img2)
        assertFalse(result.match)
        assertEquals(2L, result.differentPixels)
        assertEquals(100.0, result.mismatchPercentage, 0.001)
    }

    @Test
    fun `ScreenshotResult toRgbaImage decodes valid PNG`() {
        val image = BufferedImage(2, 2, BufferedImage.TYPE_INT_ARGB)
        image.setRGB(0, 0, 0xFFFF0000.toInt()) // Red
        image.setRGB(1, 0, 0xFF00FF00.toInt()) // Green
        image.setRGB(0, 1, 0xFF0000FF.toInt()) // Blue
        image.setRGB(1, 1, 0xFFFFFFFF.toInt()) // White

        val baos = ByteArrayOutputStream()
        ImageIO.write(image, "png", baos)
        val pngBytes = baos.toByteArray()

        val screenshotResult = ScreenshotResult(pngBytes, 2, 2)
        val rgba = screenshotResult.toRgbaImage()

        assertNotNull(rgba)
        assertEquals(2, rgba!!.width)
        assertEquals(2, rgba.height)
        // First pixel: Red (255, 0, 0, 255)
        assertEquals(255.toByte(), rgba.pixels[0])
        assertEquals(0.toByte(), rgba.pixels[1])
        assertEquals(0.toByte(), rgba.pixels[2])
        assertEquals((-1).toByte(), rgba.pixels[3]) // 255 as signed byte
    }

    @Test
    fun `ScreenshotResult toRgbaImage returns null for invalid bytes`() {
        val screenshotResult = ScreenshotResult(ByteArray(0), 0, 0)
        assertNull(screenshotResult.toRgbaImage())

        val invalidResult = ScreenshotResult(byteArrayOf(0x01, 0x02, 0x03), 0, 0)
        assertNull(invalidResult.toRgbaImage())
    }
}
