#!/usr/bin/env python3
"""Refresh pinned browser libraries after verifying npm tarball integrity.

Run with --check to verify the checked-in source and provenance without changes.
The versions are deliberately pinned; update them alongside dependency review.
"""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / 'kmpwright-core/src/commonMain/kotlin/com/bernaferrari/kmpwright/core/generated'
PACKAGES = [
    ('react', '19.3.0', 'cjs/react.development.js', 'ReactRuntimeBundle', 'reactRuntimeBundle',
     'https://github.com/react/react', 'MIT', ['LICENSE']),
    ('react-devtools-inline', '8.0.0', 'dist/backend.js', 'ReactDevToolsBundle', 'reactDevToolsBundle',
     'https://github.com/react/react', 'MIT', []),
    ('web-vitals', '6.2.3', 'dist/web-vitals.iife.js', 'WebVitalsBundle', 'webVitalsBundle',
     'https://github.com/GoogleChrome/web-vitals', 'Apache-2.0', ['LICENSE']),
    ('axe-core', '4.14.0', 'axe.min.js', 'AxeBundle', 'axeBundle',
     'https://github.com/dequelabs/axe-core', 'MPL-2.0', ['LICENSE', 'LICENSE-3RD-PARTY.txt']),
]


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def kotlin_source(bundle, filename, property_name, name, version):
    # Keep each string below the JVM's 64 KiB constant limit. A function joins
    # chunks at runtime, avoiding constant folding into one oversized string.
    chunks = [bundle[i:i + 12_000] for i in range(0, len(bundle), 12_000)]
    literals = [json.dumps(chunk, ensure_ascii=True).replace('$', '\\$') for chunk in chunks]
    return ('// Generated by scripts/update-browser-bundles.py; do not edit.\n'
            f'// Unmodified {name} {version}; see docs/licenses for provenance.\n'
            'package com.bernaferrari.kmpwright.core.generated\n\n'
            f'internal fun {property_name}(): String = listOf(\n' +
            ',\n'.join('    ' + literal for literal in literals) + '\n).joinToString("")\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, version, bundle_path, filename, property_name, repository, license_id, licenses in PACKAGES:
        metadata = json.loads(fetch(f'https://registry.npmjs.org/{name}/{version}'))
        archive = fetch(metadata['dist']['tarball'])
        algorithm, expected = metadata['dist']['integrity'].split('-', 1)
        actual = base64.b64encode(hashlib.new(algorithm, archive).digest()).decode()
        if actual != expected:
            raise RuntimeError(f'{name}: registry integrity mismatch')
        with tarfile.open(fileobj=io.BytesIO(archive), mode='r:gz') as tar:
            bundle = tar.extractfile(f'package/{bundle_path}').read()
            outputs = {GENERATED / f'{filename}.kt': kotlin_source(bundle.decode(), filename, property_name, name, version).encode()}
            for license_file in licenses:
                destination = f'{name}-{license_id}.txt' if license_file == 'LICENSE' else f'{name}-THIRD-PARTY.txt'
                outputs[ROOT / 'docs/licenses' / destination] = tar.extractfile(f'package/{license_file}').read()
        if name == 'react-devtools-inline':
            source_commit = metadata['gitHead']
            outputs[ROOT / 'docs/licenses/react-devtools-inline-MIT.txt'] = fetch(
                f'https://raw.githubusercontent.com/react/react/{source_commit}/LICENSE')
            bundled_libraries = [('compare-versions', '5.0.3'), ('lru-cache', '5.1.1'),
                                 ('yallist', '3.1.1'), ('process', '0.11.10'),
                                 ('error-stack-parser', '2.0.6'), ('stackframe', '1.1.1')]
            notices = []
            for library, library_version in bundled_libraries:
                library_metadata = json.loads(fetch(f'https://registry.npmjs.org/{library}/{library_version}'))
                library_archive = fetch(library_metadata['dist']['tarball'])
                algorithm, expected = library_metadata['dist']['integrity'].split('-', 1)
                if base64.b64encode(hashlib.new(algorithm, library_archive).digest()).decode() != expected:
                    raise RuntimeError(f'{library}: registry integrity mismatch')
                with tarfile.open(fileobj=io.BytesIO(library_archive), mode='r:gz') as tar:
                    candidates = [entry for entry in tar if entry.name.split('/')[-1].lower() in
                                  ['license', 'license.md', 'license.txt', 'licence', 'license-mit']]
                    if not candidates:
                        raise RuntimeError(f'{library}: missing license')
                    notices.append(f'{library} {library_version} ({library_metadata["license"]})\n' +
                                   tar.extractfile(candidates[0]).read().decode())
            outputs[ROOT / 'docs/licenses/react-devtools-inline-THIRD-PARTY.txt'] = ('\n\n'.join(notices) + '\n').encode()
        provenance = dict(name=name, version=version, repository=repository, license=license_id,
                          registryIntegrity=metadata['dist']['integrity'], bundle=bundle_path,
                          sha256=hashlib.sha256(bundle).hexdigest())
        if name == 'react-devtools-inline':
            provenance['sourceCommit'] = source_commit
            provenance['bundledLibraries'] = [dict(name=n, version=v) for n, v in bundled_libraries]
        outputs[ROOT / f'docs/licenses/{name}-provenance.json'] = (json.dumps(provenance, indent=2) + '\n').encode()
        for path, content in outputs.items():
            if args.check:
                if not path.exists() or path.read_bytes() != content:
                    raise RuntimeError(f'Generated file differs: {path.relative_to(ROOT)}')
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
        print(f'{name} {version}: integrity verified, {len(bundle)} bundle bytes')


if __name__ == '__main__':
    main()
