#!/usr/bin/env python3
"""Regenerate reviewed React inspection adapters from the pinned comparison.

The Kotlin API owns policy, serialization, synchronization and lifecycle.
These Apache-2.0 script adaptations retain agent-browser attribution.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
COMMIT = 'd9570915f4dd6504dee4070379d2c4f79d81dbb2'
SOURCE = f'https://raw.githubusercontent.com/vercel-labs/agent-browser/{COMMIT}/cli/src/native/react/scripts.rs'
NAMES = {'TREE_SNAPSHOT': 'reactTreeScript', 'TREE_INSPECT': 'reactInspectScript',
         'RENDERS_INIT': 'reactRendersInitScript', 'RENDERS_STOP': 'reactRendersStopScript',
         'SUSPENSE_WALK': 'reactSuspenseScript'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with urllib.request.urlopen(SOURCE, timeout=30) as response:
        source = response.read()
    scripts = dict(re.findall(r'pub const (\w+): &str = r#"(.*?)"#;', source.decode(), re.S))
    spec = importlib.util.spec_from_file_location('bundles', ROOT / 'scripts/update-browser-bundles.py')
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    parts = ['// Adapted from agent-browser (Apache-2.0); see THIRD_PARTY_NOTICES.md.\n'
             '// Generated by scripts/update-react-scripts.py; do not edit.\n'
             'package com.bernaferrari.kmpwright.core.generated\n\n']
    for key, name in NAMES.items():
        script = scripts[key].replace('{{PICK_RI}}', scripts['PICK_REACT_RENDERER']).replace('__ab', '__kmpwright')
        script = script.replace('relaunch with --enable react-devtools', 'call page.react.enable() before loading the React application')
        if key in ['TREE_SNAPSHOT', 'SUSPENSE_WALK']:
            script = script.replace('  const batches = await', '  let operationCount = 0, overflow = false, captureActive = true;\n  const batches = await')
            script = script.replace('if (event === "operations") out.push(Array.from(payload));',
                                    'if (captureActive && event === "operations") { operationCount += payload.length; if (operationCount <= 1000000) out.push(Array.from(payload)); else overflow = true; }')
            script = script.replace('if (event === "operations") out.push(payload);',
                                    'if (captureActive && event === "operations") { operationCount += payload.length; if (operationCount <= 1000000) out.push(Array.from(payload)); else overflow = true; }')
            script = script.replace('    ri.flushInitialOperations();',
                                    '    try { ri.flushInitialOperations(); } catch(error) { hook.emit = origEmit; throw error; }')
            script = script.replace('  const nodes = batches', '  if (overflow) throw new Error("React tree exceeds operation budget");\n  const nodes = batches')
            script = script.replace('  const boundaryMap = new Map();', '  if (overflow) throw new Error("React Suspense tree exceeds operation budget");\n  const boundaryMap = new Map();')
            script = script.replace('hook.emit = function (event, payload)', 'const captureEmit = hook.emit = function (event, payload)')
            script = script.replace('hook.emit = origEmit;', 'if(hook.emit===captureEmit)hook.emit=origEmit;captureActive=false;')
        if key == 'RENDERS_INIT':
            script = script.replace('  function getName(fiber)', '  window.__AB_RENDERS_COMMIT__ = hook.onCommitFiberRoot;\n  function getName(fiber)')
            script = script.replace('  const data = {};', '  const captureToken={active:true}; window.__AB_RENDERS_TOKEN__=captureToken;\n  const data = {};')
            script = script.replace('try { walkFiber(root.current); } catch {}', 'try { if(captureToken.active)walkFiber(root.current); } catch {}')
            script = script.replace('const data = {};', 'const data = Object.create(null);')
            script = script.replace('const fps = { frames: [], last: 0, rafId: 0 };',
                                    'const fps = {sum:0,count:0,min:Infinity,max:0,drops:0,last:0,rafId:0};')
            script = script.replace('if (fps.last > 0) fps.frames.push(now - fps.last);',
                                    'if (fps.last > 0 && now > fps.last) { const sample=1000/(now-fps.last); fps.sum+=sample; fps.count++; fps.min=Math.min(fps.min,sample); fps.max=Math.max(fps.max,sample); if(sample<30)fps.drops++; }')
            script = script.replace('changes: [], _instances: new Set(),', 'changes: [], _instances: new WeakSet(), _instanceCount: 0,')
            script = script.replace('if (!data[name]._instances.has(fiber)) {',
                                    'if (!data[name]._instances.has(fiber) && !(fiber.alternate && data[name]._instances.has(fiber.alternate))) {\n              data[name]._instanceCount++;')
            script = script.replace('function walkFiber(fiber) {', 'function visitFiber(fiber) {')
            script = script.replace('    walkFiber(fiber.child);\n    walkFiber(fiber.sibling);', '')
            script = script.replace('  function visitFiber(fiber) {',
                                    '  function walkFiber(root) { const stack=[root], seen=new WeakSet(); let count=0; while(stack.length && count++<50000) { const f=stack.pop(); if(!f||seen.has(f))continue; seen.add(f); visitFiber(f); if(f.sibling)stack.push(f.sibling); if(f.child)stack.push(f.child); } }\n  function visitFiber(fiber) {')
        if key == 'RENDERS_STOP':
            script = script.replace('if (hook) hook.onCommitFiberRoot = orig || undefined;',
                                    'if(window.__AB_RENDERS_TOKEN__)window.__AB_RENDERS_TOKEN__.active=false;\n  if (hook && hook.onCommitFiberRoot === window.__AB_RENDERS_COMMIT__) hook.onCommitFiberRoot = orig || undefined;\n  delete window.__AB_RENDERS_TOKEN__;delete window.__AB_RENDERS_COMMIT__;')
            a = script.index('    if (fpsData.frames.length > 0)')
            b = script.index('\n  const hook', a)
            script = script[:a] + '''    if (fpsData.count > 0) fpsStats = {avg:Math.round(fpsData.sum/fpsData.count), min:Math.round(fpsData.min), max:Math.round(fpsData.max), drops:fpsData.drops};
  }
''' + script[b:]
            script = script.replace('instanceCount: entry._instances.size', 'instanceCount: entry._instanceCount')
        source_part = generator.kotlin_source(script, '', name, 'agent-browser React adapter', COMMIT)
        parts.append(source_part.split('package com.bernaferrari.kmpwright.core.generated\n\n', 1)[1] + '\n')
    outputs = {ROOT / 'kmpwright-core/src/commonMain/kotlin/com/bernaferrari/kmpwright/core/generated/ReactScripts.kt': (''.join(parts).rstrip() + '\n').encode(),
               ROOT / 'docs/licenses/react-scripts-provenance.json': (json.dumps(dict(source=SOURCE, commit=COMMIT,
                  sha256=hashlib.sha256(source).hexdigest(), adaptations=['Kotlin API errors and private names',
                  'bounded operation capture', 'constant-memory FPS statistics', 'weak instance tracking',
                  'iterative bounded fiber traversal', 'hook restoration after flush failure', 'conditional hook ownership restoration and inactive capture tokens']), indent=2)+'\n').encode()}
    for path, content in outputs.items():
        if args.check:
            if path.read_bytes() != content:
                raise RuntimeError(f'Generated adapter differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print('React inspection adapters verified against pinned upstream source')


if __name__ == '__main__':
    main()
